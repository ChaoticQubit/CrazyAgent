#[test]
fn ts_a_codec_name_taken_by_a_capability_is_refused() {
    for name in ["encode_blob", "decode_blob"] {
        let source = format!(
            "type Blob {{ size: u64 }}\ncapability x.{name}(blob: Blob) -> unit\n  tier: t1\n  needs: x.y\n"
        );
        let error = refused(&[("x", &source)]);
        assert_eq!(error.code, "capgen_name_collision", "{name}: {error:?}");
        assert_eq!(error.file, "x.cap");
    }
    let unmapped = "type Blob { size: u16 }\ncapability x.encode_blob(blob: Blob) -> unit\n  tier: t1\n  needs: x.y\n";
    assert!(ts(&parsed(&[("x", unmapped)])).is_ok());
    let alias = refused(&[
        ("secrets", "handle Secret"),
        (
            "net",
            "capability net.secrets(key: secrets.Secret) -> unit\n  tier: t1\n  needs: net.y\n",
        ),
    ]);
    assert_eq!(alias.code, "capgen_name_collision", "{alias:?}");
    let twice = refused(&[(
        "x",
        "capability x.a_1(a: u16) -> unit\n  tier: t1\n  needs: x.y\ncapability x.a1(a: u16) -> unit\n  tier: t1\n  needs: x.y\n",
    )]);
    assert_eq!(twice.code, "capgen_name_collision", "{twice:?}");
    let index = refused(&[("index", "type A { a: u16 }")]);
    assert_eq!(index.code, "capgen_reserved_name", "{index:?}");
    assert_eq!(index.detail, "ts: index");
}

#[test]
fn ts_a_reserved_name_is_refused() {
    for (stem, source, name) in [
        (
            "x",
            "capability x.delete(a: u16) -> unit\n  tier: t1\n  needs: x.y\n",
            "delete",
        ),
        (
            "x",
            "capability x.go(new: u16) -> unit\n  tier: t1\n  needs: x.y\n",
            "new",
        ),
        ("x", "type Wire { a: u16 }", "Wire"),
        ("class", "type A { a: u16 }", "class"),
    ] {
        let error = refused(&[(stem, source)]);
        assert_eq!(error.code, "capgen_reserved_name", "{name}: {error:?}");
        assert_eq!(error.detail, format!("ts: {name}"));
        assert_eq!(error.file, format!("{stem}.cap"));
    }
}

#[test]
fn ts_output_is_lf_with_one_trailing_newline_and_no_tab() {
    let mut all = ts(&parsed(&[("settings", SETTINGS)])).expect("generates");
    for folder in FIXTURES {
        all.extend(fixture_ts(folder));
    }
    for (path, text) in &all {
        assert!(!text.contains('\r'), "{path} holds a CR");
        assert!(!text.contains('\t'), "{path} holds a tab");
        assert!(text.ends_with('\n'), "{path} ends without a newline");
        assert!(!text.ends_with("\n\n"), "{path} ends in a blank line");
        for line in text.lines() {
            let named = line.trim_start().starts_with("/**") && line.contains(".cap");
            assert!(line.len() <= 100 || named, "{path} line over 100: {line}");
        }
    }
}


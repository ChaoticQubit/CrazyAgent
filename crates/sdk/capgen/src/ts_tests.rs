#[test]
fn ts_only_name_lines_pass_100_columns() {
    let pascal = format!("A{}", "b".repeat(63));
    let snake = format!("a{}", "_b".repeat(31)) + "c";
    let handle = format!("H{}", "c".repeat(63));
    let variant = format!("v{}", "d".repeat(63));
    let other = format!("w{}", "e".repeat(63));
    let type_code = pascal.to_ascii_lowercase();
    let names = [&pascal, &snake, &handle, &variant, &other, &type_code];
    assert!(names.iter().all(|name| name.len() == 64), "{names:?}");
    let source = format!(
        "enum E {{ {variant}, {other} }}\nhandle {handle}\n\
         type {pascal} {{ {snake}: list<option<u64>>, {other}: E, h: {handle} }}\n\
         capability x.go({snake}: {pascal}, {other}: list<bytes>) -> {pascal}\n  tier: t1\n  needs: x.y\n"
    );
    let files = ts(&parsed(&[("x", &source)])).expect("generates");
    for (path, text) in &files {
        for line in text.lines() {
            assert!(
                line.len() <= 100 || names.iter().any(|name| line.contains(name.as_str())),
                "{path} line over 100 without a long name: {line}"
            );
        }
    }
    let x = text(&files, "x.ts");
    assert!(x.contains("export function go(\n  host: Host,\n"), "{x}");
}

#[test]
fn ts_imports_name_only_what_the_file_uses() {
    let wire = fixture_ts("fixture_wire");
    let wire = text(&wire, "wire.ts");
    assert!(
        wire.contains(
            "\nimport type { Capability, Host, Result, Wire } from \"../core.ts\";\n\
         import { call, decodeBytes, decodeU64, encodeBytes, encodeU64 } from \"../core.ts\";\n"
        ),
        "{wire}"
    );
    let codecs = ts(&parsed(&[("x", "type A { a: u64 }")])).expect("generates");
    let codecs = text(&codecs, "x.ts");
    assert!(codecs.contains(
        "\nimport type { Wire } from \"../core.ts\";\nimport { decodeU64, encodeU64 } from \"../core.ts\";\n"
    ), "{codecs}");
    let plain = ts(&parsed(&[("x", "type A { a: u16 }")])).expect("generates");
    assert!(!text(&plain, "x.ts").contains("import"));
    let two = fixture_ts("fixture_two");
    assert!(!text(&two, "net.ts").contains("../core.ts"));
    let calls = ts(&parsed(&[
        ("secrets", "handle Secret"),
        (
            "net",
            "capability net.open(key: secrets.Secret) -> unit\n  tier: t1\n  needs: net.y\n",
        ),
    ]))
    .expect("generates");
    let net = text(&calls, "net.ts");
    assert!(
        net.contains("\nimport type * as secrets from \"./secrets.ts\";\n"),
        "{net}"
    );
    assert!(net.contains("key: secrets.Secret"), "{net}");
    assert!(!net.contains("Wire"), "{net}");
}

/// Times 1000 runs of `ts` over the three fixtures and the in-test settings source and
/// checks the p95 against the budget of the `OVERHEAD_MAC` condition (quiet 1 ms, loaded
/// 5 ms). Run it as
/// `OVERHEAD_MAC=quiet cargo test --release -p crazyagent-capgen --lib ts_tests::ts_generation_p95 -- --ignored --nocapture`.
#[test]
#[ignore = "speed reading, run by name with OVERHEAD_MAC set"]
fn ts_generation_p95() {
    let condition = std::env::var("OVERHEAD_MAC").expect("OVERHEAD_MAC is quiet or loaded");
    let budget_us = match condition.as_str() {
        "quiet" => 1_000,
        "loaded" => 5_000,
        other => panic!("OVERHEAD_MAC is quiet or loaded, not {other}"),
    };
    let mut inputs: Vec<Vec<(String, File)>> = FIXTURES
        .iter()
        .map(|folder| load(&sdk(&format!("capgen/{folder}"))).expect("the fixture loads"))
        .collect();
    inputs.push(vec![(
        "settings".to_owned(),
        crazyagent_cap::parse_as("settings", SETTINGS).expect("parses"),
    )]);
    let inputs: Vec<Vec<(&str, File)>> = inputs
        .iter()
        .map(|files| {
            files
                .iter()
                .map(|(stem, file)| (stem.as_str(), file.clone()))
                .collect()
        })
        .collect();
    let mut samples: Vec<u128> = (0..1000)
        .map(|_| {
            let start = Instant::now();
            for files in &inputs {
                std::hint::black_box(ts(files).expect("generates"));
            }
            start.elapsed().as_micros()
        })
        .collect();
    samples.sort_unstable();
    let p95 = samples[samples.len() * 95 / 100 - 1];
    println!("capgen_ts_p95_us={p95} condition={condition}");
    assert!(
        p95 <= budget_us,
        "p95 {p95} us over {budget_us} us ({condition})"
    );
}

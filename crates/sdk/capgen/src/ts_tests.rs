/// An in-test copy of `caps/settings.cap`, so a new `.cap` file under `caps/` leaves the
/// exact-text row unchanged.
const SETTINGS: &str = "enum OnQuit { keep_running, stop }
enum LeftRunning { after_hours, never }
type QuitSettings { on_quit: OnQuit, left_running: LeftRunning, hours: u16 }
capability settings.save_quit(settings: QuitSettings) -> unit
  tier: kernel
  needs: settings.write
  emits: AgentQuitSaved { settings: QuitSettings }
";

/// The `settings.ts` that `ts` writes from [`SETTINGS`].
const SETTINGS_TS: &str = r#"/** Generated by capgen from settings.cap. */
import type { Capability, Host, Result } from "../core.ts";
import { call } from "../core.ts";

/** Generated by capgen from settings.cap: enum OnQuit. */
export type OnQuit = "keep_running" | "stop";

/** Generated by capgen from settings.cap: enum LeftRunning. */
export type LeftRunning = "after_hours" | "never";

/** Generated by capgen from settings.cap: type QuitSettings. */
export type QuitSettings = {
  readonly on_quit: OnQuit;
  readonly left_running: LeftRunning;
  readonly hours: number;
};

/** Generated by capgen from settings.cap: the facts of capability settings.save_quit. */
export const SAVE_QUIT: Capability = {
  name: "settings.save_quit",
  tier: "kernel",
  needs: "settings.write",
};

/** Generated by capgen from settings.cap: calls settings.save_quit through the bus.
 * Inputs: the host the kernel bound to this plugin and the call's inputs.
 * Output: the call's result, or the bus refusal. */
export function saveQuit(host: Host, settings: QuitSettings): Promise<Result<null>> {
  return call(host, SAVE_QUIT, { settings }, () => null);
}
"#;

/// The call function block that ends [`SETTINGS_TS`].
const SETTINGS_CALL: &str = r#"
/** Generated by capgen from settings.cap: calls settings.save_quit through the bus.
 * Inputs: the host the kernel bound to this plugin and the call's inputs.
 * Output: the call's result, or the bus refusal. */
export function saveQuit(host: Host, settings: QuitSettings): Promise<Result<null>> {
  return call(host, SAVE_QUIT, { settings }, () => null);
}
"#;

/// The `index.ts` that `ts` writes from [`SETTINGS`] alone.
const SETTINGS_INDEX_TS: &str = r#"/** Generated by capgen: one module per `.cap` file, and every capability once. */
import type { Capability } from "../core.ts";
import * as settings from "./settings.ts";

export { settings };

/** Generated by capgen: every capability, once, in file then `.cap` order. */
export const CAPABILITIES: readonly Capability[] = [settings.SAVE_QUIT];
"#;

/// The three capgen fixture folders whose TS goldens sit under `ts/src/<folder>`.
const FIXTURES: [&str; 3] = ["fixture", "fixture_two", "fixture_wire"];

/// Names a folder of the sdk tree. Input: its path below `crates/sdk`. Output: the folder.
fn sdk(path: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(path)
}

/// Parses `.cap` sources named by their stems. Input: stems with sources.
/// Output: the stems with their parsed files; panics on a grammar refusal.
fn parsed<'s>(sources: &[(&'s str, &str)]) -> Vec<(&'s str, File)> {
    sources
        .iter()
        .map(|(stem, source)| {
            (
                *stem,
                crazyagent_cap::parse_as(stem, source).expect("parses"),
            )
        })
        .collect()
}

/// Writes the TS for one capgen fixture folder. Input: the folder below `capgen`.
/// Output: the generated files.
fn fixture_ts(folder: &str) -> Vec<(String, String)> {
    let loaded = load(&sdk(&format!("capgen/{folder}"))).expect("the fixture loads");
    let borrowed: Vec<(&str, File)> = loaded
        .iter()
        .map(|(stem, file)| (stem.as_str(), file.clone()))
        .collect();
    ts(&borrowed).expect("the fixture generates")
}

/// The text of one generated file. Inputs: the files and the path. Output: the text;
/// panics when the path is missing.
fn text<'f>(files: &'f [(String, String)], path: &str) -> &'f str {
    files
        .iter()
        .find(|(name, _)| name == path)
        .map(|(_, text)| text.as_str())
        .unwrap_or_else(|| panic!("{path} is generated"))
}

/// Runs `ts` over sources that must be refused. Input: stems with sources.
/// Output: the refusal; panics when `ts` accepts them.
fn refused(sources: &[(&str, &str)]) -> CapgenError {
    match ts(&parsed(sources)) {
        Ok(files) => panic!("generated, expected a refusal: {files:?}"),
        Err(error) => error,
    }
}

/// Reads one numeric const from a source file. Inputs: the file's text and the const's
/// name. Output: the value written after `=` up to `;`, with `_` dropped.
fn const_value(source: &str, name: &str) -> u64 {
    let line = source
        .lines()
        .find(|line| line.contains(&format!("const {name}")))
        .unwrap_or_else(|| panic!("{name} is declared"));
    let (_, value) = line.split_once('=').expect("the const has a value");
    value
        .trim()
        .trim_end_matches(';')
        .replace('_', "")
        .parse()
        .unwrap_or_else(|_| panic!("{name} is a number: {line}"))
}

#[test]
fn ts_settings_text_is_exact() {
    let files = ts(&parsed(&[("settings", SETTINGS)])).expect("generates");
    assert_eq!(
        files
            .iter()
            .map(|(path, _)| path.as_str())
            .collect::<Vec<_>>(),
        vec!["index.ts", "settings.ts"]
    );
    assert_eq!(text(&files, "settings.ts"), SETTINGS_TS);
    assert_eq!(text(&files, "index.ts"), SETTINGS_INDEX_TS);
}

#[test]
fn ts_fixtures_generate_the_checked_in_goldens() {
    for folder in FIXTURES {
        let files = fixture_ts(folder);
        assert_eq!(
            crate::drift(&sdk(&format!("ts/src/{folder}")), &files),
            Vec::<String>::new(),
            "{folder}"
        );
    }
}

#[test]
fn ts_generation_is_byte_stable_in_any_file_order() {
    let net = fs::read_to_string(sdk("capgen/fixture_two/net.cap")).expect("net.cap reads");
    let secrets =
        fs::read_to_string(sdk("capgen/fixture_two/secrets.cap")).expect("secrets.cap reads");
    let forward = ts(&parsed(&[("net", &net), ("secrets", &secrets)])).expect("generates");
    let backward = ts(&parsed(&[("secrets", &secrets), ("net", &net)])).expect("generates");
    assert_eq!(forward, backward);
    assert_eq!(fixture_ts("fixture_two"), fixture_ts("fixture_two"));
    assert_eq!(fixture_ts("fixture_two"), forward);
}

#[test]
fn ts_types_follow_the_mapping_table() {
    let wire = fixture_ts("fixture_wire");
    let wire = text(&wire, "wire.ts");
    for line in [
        "export type Mode = \"read\" | \"write\";",
        "  readonly size: bigint;",
        "  readonly data: Uint8Array;",
        "  readonly parts: readonly bigint[];",
        "  readonly tail: Uint8Array | null;",
        "  readonly name: string;",
        "  readonly mode: Mode;",
    ] {
        assert!(wire.lines().any(|held| held == line), "{line} in {wire}");
    }
    let fixture = fixture_ts("fixture");
    let fixture = text(&fixture, "fixture.ts");
    for line in [
        "  readonly status: number;",
        "  readonly headers: readonly Header[];",
        "  readonly timeout_ms: number | null;",
        "  readonly grid: readonly (readonly string[])[];",
        "  readonly extra: Header | null;",
        "  readonly secret: Secret;",
    ] {
        assert!(
            fixture.lines().any(|held| held == line),
            "{line} in {fixture}"
        );
    }
    let flags = ts(&parsed(&[(
        "x",
        "type A { a: list<option<u16>>, b: bool }",
    )]))
    .expect("generates");
    let flags = text(&flags, "x.ts");
    assert!(flags.contains("  readonly a: readonly (number | null)[];\n"));
    assert!(flags.contains("  readonly b: boolean;\n"));
}


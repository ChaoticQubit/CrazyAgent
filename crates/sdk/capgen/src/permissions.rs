use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use crazyagent_cap::{File, Tier};
use kernel_plugin_host::manifest;
use kernel_plugin_host::permission;

use crate::CapgenError;

/// The most bundled code plugins one grant table may hold.
const BUNDLED_PLUGINS_MAX: usize = 1_024;

/// The tier folders a bundled plugin may sit in, one per plugin tier.
const TIER_FOLDERS: [&str; 3] = ["t1", "t2", "t3"];

/// One bundled plugin as its `plugin.toml` grants it: id, tier, permissions, whether it is
/// essential, the capability stems it serves and the file it was read from.
struct Grant {
    plugin: String,
    tier: permission::Tier,
    permissions: Vec<String>,
    essential: bool,
    capabilities: Vec<String>,
    file: String,
}

/// Writes plugin_host's `permissions.rs`: every capability's tier, permission and events,
/// sorted by name, and every bundled code plugin's grant, sorted by id. Inputs: the parsed
/// `.cap` files after every check the Rust SDK runs, and the plugins folder holding
/// `t1`/`t2`/`t3` tier folders. Output: the one file, or the first refusal.
pub(crate) fn files(
    files: &[(&str, File)],
    plugins: &Path,
) -> Result<Vec<(String, String)>, CapgenError> {
    crate::rust::files(files)?;
    let grants = bundled(plugins)?;
    served(files, &grants)?;
    let mut capabilities: Vec<_> = files
        .iter()
        .flat_map(|(_, file)| file.capabilities.iter())
        .collect();
    capabilities.sort_by(|a, b| a.name.cmp(&b.name));
    assert!(
        capabilities
            .windows(2)
            .all(|pair| pair[0].name < pair[1].name)
    );
    let mut text = String::from(
        "use crate::permission::{BundledGrant, Permission, Tier};\n\n\
         /// Generated by capgen from the `.cap` files: every capability's tier, needed\n\
         /// permission and emitted event kinds, sorted by name.\n",
    );
    text.push_str(&format!(
        "pub const PERMISSIONS: [Permission; {}] = [\n",
        capabilities.len()
    ));
    for capability in &capabilities {
        let emits: Vec<String> = capability
            .emits
            .iter()
            .map(|event| format!("{:?}", event.kind))
            .collect();
        text.push_str(&format!(
            "Permission {{ name: {:?}, tier: Tier::{}, needs: {:?}, emits: &[{}] }},\n",
            capability.name,
            tier_name(capability.tier),
            capability.needs,
            emits.join(", ")
        ));
    }
    text.push_str(
        "];\n\n\
         /// Generated by capgen from every bundled code plugin's `plugin.toml`: its tier, held\n\
         /// permissions, essential mark and served capability stems, sorted by plugin id.\n",
    );
    text.push_str(&format!(
        "pub const BUNDLED_GRANTS: [BundledGrant; {}] = [\n",
        grants.len()
    ));
    for grant in &grants {
        let held: Vec<String> = grant
            .permissions
            .iter()
            .map(|permission| format!("{permission:?}"))
            .collect();
        let stems: Vec<String> = grant
            .capabilities
            .iter()
            .map(|stem| format!("{stem:?}"))
            .collect();
        text.push_str(&format!(
            "BundledGrant {{ plugin: {:?}, tier: Tier::{:?}, permissions: &[{}], essential: {}, capabilities: &[{}] }},\n",
            grant.plugin,
            grant.tier,
            held.join(", "),
            grant.essential,
            stems.join(", ")
        ));
    }
    text.push_str("];\n");
    Ok(vec![("permissions.rs".to_owned(), text)])
}

/// Checks the stems the bundled plugins serve against the `.cap` files: each stem is served
/// once, holds a capability, no capability of tier kernel, none below its provider's tier
/// and none that emits, and every plugin-tier capability's stem is served. Inputs: the
/// parsed files and the grants. Output: `Ok`, or `capgen_served_twice`,
/// `capgen_serves_unknown`, `capgen_serves_kernel`, `capgen_provider_tier`,
/// `capgen_served_emits` or `capgen_unserved`.
fn served(files: &[(&str, File)], grants: &[Grant]) -> Result<(), CapgenError> {
    let refuse = |file: &str, code: &'static str, detail: &str| CapgenError {
        file: file.to_owned(),
        code,
        detail: detail.to_owned(),
    };
    let capabilities: Vec<_> = files
        .iter()
        .flat_map(|(_, file)| file.capabilities.iter())
        .collect();
    let stem_of = |name: &str| name.split_once('.').map_or("", |(stem, _)| stem).to_owned();
    let mut providers: BTreeMap<&str, &str> = BTreeMap::new();
    for grant in grants {
        for stem in &grant.capabilities {
            if providers.insert(stem, &grant.plugin).is_some() {
                return Err(refuse(&grant.file, "capgen_served_twice", stem));
            }
            let mut held = capabilities
                .iter()
                .filter(|capability| stem_of(&capability.name) == *stem)
                .peekable();
            if held.peek().is_none() {
                return Err(refuse(&grant.file, "capgen_serves_unknown", stem));
            }
            for capability in held {
                if capability.tier == Tier::Kernel {
                    return Err(refuse(
                        &grant.file,
                        "capgen_serves_kernel",
                        &capability.name,
                    ));
                }
                if grant.tier > host_tier(capability.tier) {
                    return Err(refuse(
                        &grant.file,
                        "capgen_provider_tier",
                        &capability.name,
                    ));
                }
                if !capability.emits.is_empty() {
                    return Err(refuse(&grant.file, "capgen_served_emits", &capability.name));
                }
            }
        }
    }
    if let Some(capability) = capabilities.iter().find(|capability| {
        capability.tier != Tier::Kernel
            && !providers.contains_key(stem_of(&capability.name).as_str())
    }) {
        let stem = stem_of(&capability.name);
        return Err(refuse(
            &format!("{stem}.cap"),
            "capgen_unserved",
            &capability.name,
        ));
    }
    Ok(())
}

/// Writes the engine's `served.rs`: `served()` building the host crate's `Served` with one
/// field per plugin-served stem, each the `<STEM>` static of the crate of the bundled
/// plugin serving it. Inputs: the parsed `.cap` files after every check the permissions
/// mode runs, and the plugins folder. Output: the one file, none when no stem is served,
/// or the first refusal, `capgen_provider_crate` for a provider folder whose `Cargo.toml`
/// does not name the package `crazyagent-plugin-<id>` inside its `[package]` table.
/// Each id reaches the Rust path only after `manifest::read` refused any id outside the
/// plugin id grammar (`is_plugin_id`, plugin_host `manifest.rs`).
pub(crate) fn served_wiring(
    files: &[(&str, File)],
    plugins: &Path,
) -> Result<Vec<(String, String)>, CapgenError> {
    crate::rust::files(files)?;
    let grants = bundled(plugins)?;
    served(files, &grants)?;
    let mut fields: Vec<(&str, String)> = Vec::new();
    for grant in grants.iter().filter(|grant| !grant.capabilities.is_empty()) {
        let package = format!("crazyagent-plugin-{}", grant.plugin);
        let manifest = Path::new(&grant.file).with_file_name("Cargo.toml");
        let named = fs::read_to_string(&manifest)
            .is_ok_and(|text| package_named(&text, &format!("name = \"{package}\"")));
        if !named {
            return Err(CapgenError {
                file: manifest.display().to_string(),
                code: "capgen_provider_crate",
                detail: package,
            });
        }
        let krate = package.replace('-', "_");
        for stem in &grant.capabilities {
            fields.push((
                stem,
                format!("{stem}: &{krate}::{}", stem.to_ascii_uppercase()),
            ));
        }
    }
    if fields.is_empty() {
        return Ok(Vec::new());
    }
    fields.sort();
    assert!(fields.windows(2).all(|pair| pair[0].0 < pair[1].0));
    let body: Vec<String> = fields.into_iter().map(|(_, field)| field).collect();
    let text = format!(
        "/// Generated by capgen from the bundled plugins' `plugin.toml` files: the code serving\n\
         /// each plugin-served capability namespace, from the crate of the plugin that serves it.\n\
         pub fn served() -> sdk_host::generated::Served<'static> {{\n\
         sdk_host::generated::Served {{ {} }}\n}}\n",
        body.join(", ")
    );
    Ok(vec![("served.rs".to_owned(), text)])
}

/// Whether a `Cargo.toml` text holds the given `name` line inside its `[package]` table,
/// tracking table headers line by line. Inputs: the manifest text and the exact line.
/// Output: true when the line sits under `[package]` and nowhere else decides it.
fn package_named(text: &str, line: &str) -> bool {
    let mut table = "";
    text.lines().map(str::trim).any(|entry| {
        if entry.starts_with('[') {
            table = entry;
        }
        table == "[package]" && entry == line
    })
}

/// The plugin_host tier of a `.cap` tier. Input: the tier. Output: the same tier.
fn host_tier(tier: Tier) -> permission::Tier {
    match tier {
        Tier::Kernel => permission::Tier::Kernel,
        Tier::T1 => permission::Tier::T1,
        Tier::T2 => permission::Tier::T2,
        Tier::T3 => permission::Tier::T3,
    }
}

/// The Rust name of a `.cap` tier in plugin_host's `Tier`. Input: the tier. Output: its
/// variant name.
fn tier_name(tier: Tier) -> &'static str {
    match tier {
        Tier::Kernel => "Kernel",
        Tier::T1 => "T1",
        Tier::T2 => "T2",
        Tier::T3 => "T3",
    }
}

/// Reads every bundled code plugin's `plugin.toml` below the tier folders, skipping any
/// non-folder entry. Input: the plugins folder. Output: the grants sorted by plugin id,
/// or `capgen_read`, `capgen_plugin_tier` (a folder outside `t1`/`t2`/`t3`, or a manifest
/// tier unlike its folder), `capgen_plugin_folder` (an id unlike its folder),
/// `capgen_plugin_duplicate`, `capgen_too_many_plugins` or the manifest's own refusal.
fn bundled(plugins: &Path) -> Result<Vec<Grant>, CapgenError> {
    let refuse = |file: &Path, code: &'static str, detail: String| CapgenError {
        file: file.display().to_string(),
        code,
        detail,
    };
    let mut grants: Vec<Grant> = Vec::new();
    for tier_dir in folders(plugins)? {
        let word = tier_dir
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("");
        if !TIER_FOLDERS.contains(&word) {
            return Err(refuse(&tier_dir, "capgen_plugin_tier", word.to_owned()));
        }
        let tier = permission::Tier::from_word(word).expect("a tier folder names a tier");
        for dir in folders(&tier_dir)? {
            let file = dir.join("plugin.toml");
            let read = manifest::read(&dir)
                .map_err(|refused| refuse(&file, refused.code, format!("line {}", refused.line)))?;
            if read.tier != word {
                return Err(refuse(&file, "capgen_plugin_tier", read.tier));
            }
            if dir.file_name().and_then(|name| name.to_str()) != Some(read.plugin.as_str()) {
                return Err(refuse(&file, "capgen_plugin_folder", read.plugin));
            }
            if grants.iter().any(|grant| grant.plugin == read.plugin) {
                return Err(refuse(&file, "capgen_plugin_duplicate", read.plugin));
            }
            if grants.len() == BUNDLED_PLUGINS_MAX {
                return Err(refuse(plugins, "capgen_too_many_plugins", String::new()));
            }
            grants.push(Grant {
                plugin: read.plugin,
                tier,
                permissions: read.permissions,
                essential: read.essential,
                capabilities: read.capabilities,
                file: file.display().to_string(),
            });
        }
    }
    grants.sort_by(|a, b| a.plugin.cmp(&b.plugin));
    assert!(grants.len() <= BUNDLED_PLUGINS_MAX);
    assert!(
        grants
            .windows(2)
            .all(|pair| pair[0].plugin < pair[1].plugin)
    );
    Ok(grants)
}

/// The sub-folders of a folder, sorted by path, skipping any other entry. Input: the
/// folder. Output: the sub-folders, or `capgen_read`.
fn folders(dir: &Path) -> Result<Vec<std::path::PathBuf>, CapgenError> {
    let refuse = |detail: String| CapgenError {
        file: dir.display().to_string(),
        code: "capgen_read",
        detail,
    };
    let mut found = Vec::new();
    for entry in fs::read_dir(dir).map_err(|error| refuse(error.to_string()))? {
        let path = entry.map_err(|error| refuse(error.to_string()))?.path();
        if path.is_dir() {
            found.push(path);
        }
    }
    found.sort();
    Ok(found)
}

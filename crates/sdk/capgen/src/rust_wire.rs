use std::collections::{BTreeMap, BTreeSet};

use crazyagent_cap::{Capability, File, TypeRef};

use crate::CapgenError;
use crate::rust::pascal;

/// The folder below `src/generated` that holds the call envelopes, also refused as a stem.
pub(crate) const FOLDER: &str = "envelope";

/// Input names a call envelope never carries: the calling plugin's id always comes from
/// the host that loaded it, never from the wire.
const CALLER_INPUTS: [&str; 3] = ["plugin", "caller", "host"];

/// Writes the call envelopes: `envelope/mod.rs` and one `envelope/<stem>.rs` per file with
/// a capability, nothing when no file has one. Input: every file, sorted by stem, after
/// the Rust checks passed. Output: the files with their paths, or `capgen_reserved_name`
/// (the stem `envelope`, a caller input) or `capgen_name_collision`.
pub(crate) fn files(sorted: &[&(&str, File)]) -> Result<Vec<(String, String)>, CapgenError> {
    for (stem, file) in sorted {
        if *stem == FOLDER {
            return Err(refuse(stem, "capgen_reserved_name", FOLDER.to_owned()));
        }
        for capability in &file.capabilities {
            for input in &capability.inputs {
                if CALLER_INPUTS.contains(&input.name.as_str()) {
                    return Err(refuse(stem, "capgen_reserved_name", input.name.clone()));
                }
            }
        }
    }
    let called: Vec<&&(&str, File)> = sorted
        .iter()
        .filter(|(_, file)| !file.capabilities.is_empty())
        .collect();
    if called.is_empty() {
        return Ok(Vec::new());
    }
    let mut out = Vec::with_capacity(called.len() + 1);
    let mut index = String::new();
    for (stem, file) in &called {
        index.push_str(&format!(
            "/// Generated by capgen from {stem}.cap: its call envelopes.\npub mod {stem};\n"
        ));
        out.push((format!("{FOLDER}/{stem}.rs"), module(stem, file, sorted)?));
    }
    out.push((format!("{FOLDER}/mod.rs"), index));
    out.sort();
    assert_eq!(out.len(), called.len() + 1);
    Ok(out)
}

/// Builds a refusal of a file. Inputs: the stem, the code and the detail. Output: the refusal.
fn refuse(stem: &str, code: &'static str, detail: String) -> CapgenError {
    CapgenError {
        file: format!("{stem}.cap"),
        code,
        detail,
    }
}

/// What a named item of the file, or of another file, is to the wire.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Item {
    Handle,
    Enum,
    Plain,
    Mirrored,
}

/// The items of one file: each handle, enum and type by name, a type marked `Mirrored`
/// when it holds a `u64`, `bytes` or a handle at any depth, and the loaded files for the
/// foreign handles and enums.
struct Index<'f> {
    stem: &'f str,
    items: BTreeMap<&'f str, Item>,
    all: &'f [&'f (&'f str, File)],
}

impl<'f> Index<'f> {
    /// Indexes one file, each type marked once after the types its fields name, so the
    /// work stays linear in the fields. Inputs: the stem, the file and every loaded file.
    /// Output: the index.
    fn of(stem: &'f str, file: &'f File, all: &'f [&'f (&'f str, File)]) -> Self {
        let mut index = Self {
            stem,
            items: BTreeMap::new(),
            all,
        };
        for item in &file.handles {
            index.items.insert(item.name.as_str(), Item::Handle);
        }
        for item in &file.enums {
            index.items.insert(item.name.as_str(), Item::Enum);
        }
        let types: BTreeMap<&str, &crazyagent_cap::Type> = file
            .types
            .iter()
            .map(|item| (item.name.as_str(), item))
            .collect();
        for item in &file.types {
            index.mark(item.name.as_str(), &types, 0);
        }
        assert_eq!(
            index.items.len(),
            file.handles.len() + file.enums.len() + file.types.len()
        );
        index
    }

    /// Marks one type after every type its fields name. Inputs: the type's name, the
    /// file's types and how many types deep the walk is. Output: the index grows.
    fn mark(
        &mut self,
        name: &'f str,
        types: &BTreeMap<&'f str, &'f crazyagent_cap::Type>,
        depth: usize,
    ) {
        assert!(depth <= types.len());
        if self.items.contains_key(name) {
            return;
        }
        let item = types.get(name).expect("mark walks declared types");
        for field in &item.fields {
            if let Some(inner) = named_in(&field.ty)
                && let Some((key, _)) = types.get_key_value(inner)
            {
                self.mark(key, types, depth + 1);
            }
        }
        let mirrored = item.fields.iter().any(|field| self.wired(&field.ty));
        let kind = if mirrored {
            Item::Mirrored
        } else {
            Item::Plain
        };
        self.items.insert(name, kind);
    }

    /// What a named item is. Inputs: the owning stem, `None` for this file, and the name.
    /// Output: the item.
    fn item(&self, owner: Option<&str>, name: &str) -> Item {
        let Some(owner) = owner else {
            return *self
                .items
                .get(name)
                .expect("a named item is declared or marked before it is read");
        };
        let (_, file) = self
            .all
            .iter()
            .find(|(stem, _)| *stem == owner)
            .expect("every foreign ref is resolved before generation");
        if file.handles.iter().any(|item| item.name == name) {
            Item::Handle
        } else {
            assert!(file.enums.iter().any(|item| item.name == name));
            Item::Enum
        }
    }

    /// Whether a value of a type differs on the wire from its SDK serde: a `u64`, `bytes`,
    /// a handle or a mirrored type, through lists and options. Input: the type. Output:
    /// the answer.
    fn wired(&self, ty: &TypeRef) -> bool {
        match ty {
            TypeRef::U64 | TypeRef::Bytes => true,
            TypeRef::U16 | TypeRef::U32 | TypeRef::Bool | TypeRef::Text => false,
            TypeRef::List(inner) | TypeRef::Option(inner) => self.wired(inner),
            TypeRef::Named(name) => matches!(self.item(None, name), Item::Handle | Item::Mirrored),
            TypeRef::Foreign { stem, name } => self.item(Some(stem), name) == Item::Handle,
        }
    }

    /// The SDK path of a named item, from inside an envelope module. Inputs: the owning
    /// stem, `None` for this file, and the name. Output: the path.
    fn sdk_path(&self, owner: Option<&str>, name: &str) -> String {
        format!("super::super::{}::{name}", owner.unwrap_or(self.stem))
    }

    /// The Rust type of a value on the wire: `u64`, `bytes` and handles as the
    /// `crate::wire` newtypes, a mirrored type as its envelope mirror, anything else as
    /// its SDK type. Input: the type. Output: the type text.
    fn wire_type(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::U16 => "u16".to_owned(),
            TypeRef::U32 => "u32".to_owned(),
            TypeRef::Bool => "bool".to_owned(),
            TypeRef::Text => "alloc::string::String".to_owned(),
            TypeRef::U64 => "crate::wire::U64".to_owned(),
            TypeRef::Bytes => "crate::wire::Bytes".to_owned(),
            TypeRef::List(inner) => format!("alloc::vec::Vec<{}>", self.wire_type(inner)),
            TypeRef::Option(inner) => format!("core::option::Option<{}>", self.wire_type(inner)),
            TypeRef::Named(name) => match self.item(None, name) {
                Item::Handle => "crate::wire::Id".to_owned(),
                Item::Mirrored => name.clone(),
                Item::Enum | Item::Plain => self.sdk_path(None, name),
            },
            TypeRef::Foreign { stem, name } => match self.item(Some(stem), name) {
                Item::Handle => "crate::wire::Id".to_owned(),
                _ => self.sdk_path(Some(stem), name),
            },
        }
    }

    /// The Rust type of an SDK value. Input: the type. Output: the type text.
    fn sdk_type(&self, ty: &TypeRef) -> String {
        match ty {
            TypeRef::U64 => "u64".to_owned(),
            TypeRef::Bytes => "alloc::vec::Vec<u8>".to_owned(),
            TypeRef::List(inner) => format!("alloc::vec::Vec<{}>", self.sdk_type(inner)),
            TypeRef::Option(inner) => format!("core::option::Option<{}>", self.sdk_type(inner)),
            TypeRef::Named(name) => self.sdk_path(None, name),
            TypeRef::Foreign { stem, name } => self.sdk_path(Some(stem), name),
            _ => self.wire_type(ty),
        }
    }

    /// The expression that converts one value between its SDK and wire forms, the value
    /// moved. Inputs: the type, the value expression, the direction (`true` toward the
    /// wire) and the closure depth for fresh names. Output: the expression.
    fn convert(&self, ty: &TypeRef, value: &str, out: bool, depth: usize) -> String {
        assert!(depth <= crazyagent_cap::TYPE_DEPTH_MAX);
        if !self.wired(ty) {
            return value.to_owned();
        }
        match ty {
            TypeRef::List(inner) => format!(
                "{value}.into_iter().map({}).collect()",
                self.mapper(inner, out, depth)
            ),
            TypeRef::Option(inner) => format!("{value}.map({})", self.mapper(inner, out, depth)),
            _ => match self.leaf(ty, out) {
                Leaf::Call(path) => format!("{path}({value})"),
                Leaf::Field => format!("{value}.0"),
                Leaf::Id => format!("crate::wire::Id({value}.kernel_id())"),
                Leaf::Kernel(path) => format!("{path}({value}.0)"),
            },
        }
    }

    /// The function a list or option maps each item through: a path when one exists, else
    /// a closure. Inputs: the item type, the direction and the closure depth. Output: the
    /// function text.
    fn mapper(&self, ty: &TypeRef, out: bool, depth: usize) -> String {
        let nested = matches!(ty, TypeRef::List(_) | TypeRef::Option(_));
        if !nested && let Leaf::Call(path) = self.leaf(ty, out) {
            return path;
        }
        let item = format!("item{depth}");
        format!("|{item}| {}", self.convert(ty, &item, out, depth + 1))
    }

    /// How one wired leaf converts. Inputs: the leaf type, never a list or option, and the
    /// direction. Output: the conversion.
    fn leaf(&self, ty: &TypeRef, out: bool) -> Leaf {
        let (owner, name) = match ty {
            TypeRef::U64 if out => return Leaf::Call("crate::wire::U64".to_owned()),
            TypeRef::Bytes if out => return Leaf::Call("crate::wire::Bytes".to_owned()),
            TypeRef::U64 | TypeRef::Bytes => return Leaf::Field,
            TypeRef::Named(name) => (None, name.as_str()),
            TypeRef::Foreign { stem, name } => (Some(stem.as_str()), name.as_str()),
            _ => unreachable!("only wired leaves convert"),
        };
        match (self.item(owner, name), out) {
            (Item::Handle, true) => Leaf::Id,
            (Item::Handle, false) => {
                Leaf::Kernel(format!("{}::from_kernel", self.sdk_path(owner, name)))
            }
            (Item::Mirrored, true) => Leaf::Call(format!("{name}::from")),
            (Item::Mirrored, false) => Leaf::Call(format!("{}::from", self.sdk_path(owner, name))),
            (Item::Enum | Item::Plain, _) => unreachable!("an unwired leaf is not converted"),
        }
    }
}

/// How one wired leaf converts: through a function, by reading a newtype's field, by
/// wrapping a handle's kernel id, or by rebuilding a handle from an id's field.
enum Leaf {
    Call(String),
    Field,
    Id,
    Kernel(String),
}

/// The name a type refers to through its lists and options, if any. Input: the type.
/// Output: the named item's name.
fn named_in(ty: &TypeRef) -> Option<&str> {
    match ty {
        TypeRef::List(inner) | TypeRef::Option(inner) => named_in(inner),
        TypeRef::Named(name) => Some(name.as_str()),
        _ => None,
    }
}

/// Writes one file's envelope module: a mirror per mirrored type, then per capability its
/// `<Fn>Input` and `<Fn>Output`. Inputs: the stem, the file and every loaded file.
/// Output: the text, or `capgen_name_collision` when two items take one name.
fn module(stem: &str, file: &File, all: &[&(&str, File)]) -> Result<String, CapgenError> {
    let index = Index::of(stem, file, all);
    let mut taken = BTreeSet::new();
    let mut text = String::from("use serde::{Deserialize, Serialize};\n");
    for item in &file.types {
        if index.item(None, &item.name) != Item::Mirrored {
            continue;
        }
        take(stem, &mut taken, &item.name)?;
        mirror(&mut text, stem, &index, item);
    }
    for capability in &file.capabilities {
        let function = capability
            .name
            .strip_prefix(stem)
            .and_then(|rest| rest.strip_prefix('.'))
            .expect("the Rust checks keep every capability inside its file")
            .replace('.', "_");
        let pascal = pascal(&function);
        take(stem, &mut taken, &format!("{pascal}Input"))?;
        take(stem, &mut taken, &format!("{pascal}Output"))?;
        input(&mut text, stem, &index, capability, &pascal);
        output(&mut text, stem, &index, capability, &pascal);
    }
    assert!(taken.len() >= file.capabilities.len() * 2);
    Ok(text)
}

/// Takes one envelope item name. Inputs: the stem, the names taken and the name. Output:
/// nothing, or `capgen_name_collision`.
fn take(stem: &str, taken: &mut BTreeSet<String>, name: &str) -> Result<(), CapgenError> {
    if taken.insert(name.to_owned()) {
        Ok(())
    } else {
        Err(refuse(stem, "capgen_name_collision", name.to_owned()))
    }
}

/// Writes the wire mirror of one mirrored type, refusing unknown fields, and its
/// conversions to and from the SDK type. Inputs: the text, the stem, the index and the
/// type. Output: the text grows.
fn mirror(text: &mut String, stem: &str, index: &Index<'_>, item: &crazyagent_cap::Type) {
    let sdk = index.sdk_path(None, &item.name);
    let name = &item.name;
    text.push_str(&format!(
        "\n/// Generated by capgen from {stem}.cap: type {name} as the wire carries it.\n"
    ));
    text.push_str("#[derive(Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\n");
    text.push_str(&format!("pub struct {name} {{\n"));
    for field in &item.fields {
        text.push_str(&format!(
            "    pub {}: {},\n",
            field.name,
            index.wire_type(&field.ty)
        ));
    }
    text.push_str("}\n");
    for (from, to, out) in [(sdk.as_str(), name.as_str(), true), (name, &sdk, false)] {
        text.push_str(&format!(
            "\n/// Generated by capgen from {stem}.cap: converts one {name} {}.\n",
            if out {
                "to its wire form"
            } else {
                "from its wire form"
            }
        ));
        text.push_str(&format!("impl From<{from}> for {to} {{\n"));
        text.push_str("    /// Input: the value. Output: the same value in the other form.\n");
        text.push_str(&format!(
            "    fn from(value: {from}) -> Self {{\n        Self {{\n"
        ));
        for field in &item.fields {
            let place = format!("value.{}", field.name);
            text.push_str(&format!(
                "            {}: {},\n",
                field.name,
                index.convert(&field.ty, &place, out, 0)
            ));
        }
        text.push_str("        }\n    }\n}\n");
    }
}

/// Writes a capability's input envelope, refusing unknown fields, and `into_parts`, which
/// hands back the SDK inputs in `.cap` order. Inputs: the text, the stem, the index, the
/// capability and its Pascal name. Output: the text grows.
fn input(text: &mut String, stem: &str, index: &Index<'_>, capability: &Capability, pascal: &str) {
    let call = &capability.name;
    text.push_str(&format!(
        "\n/// Generated by capgen from {stem}.cap: the inputs of {call} as the wire carries them.\n"
    ));
    text.push_str("#[derive(Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\n");
    if capability.inputs.is_empty() {
        text.push_str(&format!("pub struct {pascal}Input {{}}\n"));
    } else {
        text.push_str(&format!("pub struct {pascal}Input {{\n"));
        for field in &capability.inputs {
            text.push_str(&format!(
                "    pub {}: {},\n",
                field.name,
                index.wire_type(&field.ty)
            ));
        }
        text.push_str("}\n");
    }
    text.push_str(&format!("\nimpl {pascal}Input {{\n"));
    text.push_str(
        "    /// Converts the envelope to the SDK inputs, each handle rebuilt from its kernel\n",
    );
    text.push_str(
        "    /// id for the bus to check against the caller. Output: the inputs in `.cap` order.\n",
    );
    if capability.inputs.is_empty() {
        text.push_str("    pub fn into_parts(self) {}\n}\n");
        return;
    }
    let types: Vec<String> = capability
        .inputs
        .iter()
        .map(|field| index.sdk_type(&field.ty))
        .collect();
    let values: Vec<String> = capability
        .inputs
        .iter()
        .map(|field| index.convert(&field.ty, &format!("self.{}", field.name), false, 0))
        .collect();
    let comma = if types.len() == 1 { "," } else { "" };
    text.push_str(&format!(
        "    pub fn into_parts(self) -> ({}{comma}) {{\n        ({}{comma})\n    }}\n}}\n",
        types.join(", "),
        values.join(", ")
    ));
}

/// Writes a capability's output envelope, serialized as the bare output value (`null` for
/// `unit`), built from the SDK output. Inputs: the text, the stem, the index, the
/// capability and its Pascal name. Output: the text grows.
fn output(text: &mut String, stem: &str, index: &Index<'_>, capability: &Capability, pascal: &str) {
    let call = &capability.name;
    text.push_str(&format!(
        "\n/// Generated by capgen from {stem}.cap: the output of {call} as the wire carries it.\n"
    ));
    text.push_str("#[derive(Serialize)]\n");
    let Some(ty) = capability.output.as_ref() else {
        text.push_str(&format!("pub struct {pascal}Output;\n"));
        text.push_str(&format!("\nimpl From<()> for {pascal}Output {{\n"));
        text.push_str("    /// Input: the unit output. Output: the envelope.\n");
        text.push_str("    fn from(_value: ()) -> Self {\n        Self\n    }\n}\n");
        return;
    };
    text.push_str(&format!(
        "pub struct {pascal}Output(pub {});\n",
        index.wire_type(ty)
    ));
    text.push_str(&format!(
        "\nimpl From<{}> for {pascal}Output {{\n",
        index.sdk_type(ty)
    ));
    text.push_str("    /// Input: the SDK output. Output: the envelope.\n");
    text.push_str(&format!(
        "    fn from(value: {}) -> Self {{\n        Self({})\n    }}\n}}\n",
        index.sdk_type(ty),
        index.convert(ty, "value", true, 0)
    ));
}
